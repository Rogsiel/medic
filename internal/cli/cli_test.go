func run(t *testing.T, stdin string, args ...string) (int, string, string) {
	t.Helper()
	dir := t.TempDir()
	out, _ := os.Create(filepath.Join(dir, "out"))
	errf, _ := os.Create(filepath.Join(dir, "err"))
	t.Setenv("GITHUB_ACTIONS", "")
	t.Setenv("GITLAB_CI", "")
	code := Execute("test", args, strings.NewReader(stdin), out, errf)
	out.Close()
	errf.Close()
	o, _ := os.ReadFile(out.Name())
	e, _ := os.ReadFile(errf.Name())
	return code, string(o), string(e)
}

const cfg = `version: 1
checks:
  ok:
    type: exec
    command: ["true"]
  warn:
    type: exec
    shell: exit 1
    allow_failure: true
`

func TestRunExitCodes(t *testing.T) {
	if code, out, _ := run(t, cfg, "-c", "-", "--no-color"); code != 0 || !strings.Contains(out, "healthy") {
		t.Fatalf("code %d out %q", code, out)
	}
	if code, _, _ := run(t, cfg, "-c", "-", "--fail-on", "warning", "-q"); code != 1 {
		t.Fatalf("fail-on warning: %d", code)
	}
	if code, _, errOut := run(t, "version: 1\nchecks: {a: {type: nope}}", "-c", "-"); code != 2 || !strings.Contains(errOut, "unknown check type") {
		t.Fatalf("config error: %d %q", code, errOut)
	}
	if code, _, _ := run(t, cfg, "-c", "-", "--only", "missing"); code != 2 {
		t.Fatalf("bad --only: %d", code)
	}
	if code, _, _ := run(t, cfg, "-c", "-", "--bogus"); code != 2 {
		t.Fatalf("bad flag: %d", code)
	}
}

func TestJSONToStdoutMovesHumanToStderr(t *testing.T) {
	code, out, errOut := run(t, cfg, "-c", "-", "-o", "json=-", "--no-color")
	if code != 0 {
		t.Fatal(code)
	}
	var rep map[string]any
	if err := json.Unmarshal([]byte(out), &rep); err != nil {
		t.Fatalf("stdout is not pure JSON: %v\n%s", err, out)
	}
	if rep["exit_code"].(float64) != 0 || !strings.Contains(errOut, "healthy") {
		t.Fatalf("%v / %q", rep["exit_code"], errOut)
	}
}

func TestValidateJSON(t *testing.T) {
	code, out, _ := run(t, "version: 1\nchecks: {a: {type: cpu, timeout: 5}}", "validate", "-c", "-", "--format", "json")
	if code != 2 || !strings.Contains(out, `"line": 2`) || !strings.Contains(out, "needs a unit") {
		t.Fatalf("%d %s", code, out)
	}
}

func TestCheckOneLiner(t *testing.T) {
	if code, out, _ := run(t, "", "check", "exec", "exit 3", "--set", "expect.exit=3", "--no-color"); code != 0 {
		t.Fatalf("%d %s", code, out)
	}
	if code, _, errOut := run(t, "", "check", "exec", "true", "--set", "expect.exitt=3"); code != 2 || !strings.Contains(errOut, `did you mean "exit"`) {
		t.Fatalf("%d %s", code, errOut)
	}
	if code, _, _ := run(t, "", "check", "cpu", "x"); code != 2 {
		t.Fatalf("positional for cpu accepted: %d", code)
	}
}

func TestInitTemplateIsValid(t *testing.T) {
	if _, err := config.Load("init", []byte(docs.InitTemplate()), config.Options{}); err != nil {
		t.Fatal(err)
	}
	// Commented examples must be valid once uncommented.
	var keep []string
	for _, l := range strings.Split(docs.InitTemplate(), "\n") {
		switch {
		case strings.HasPrefix(l, "  # ") && strings.HasSuffix(l, "-example:"):
			keep = append(keep, "  "+l[4:])
		case strings.HasPrefix(l, "  #   "):
			keep = append(keep, "    "+l[6:])
		default:
			keep = append(keep, l)
		}
	}
	if _, err := config.Load("init", []byte(strings.Join(keep, "\n")), config.Options{}); err != nil {
		t.Fatalf("uncommented template invalid: %v", err)
	}
}

// TestGeneratedFilesUpToDate fails when docs/ or schema/ are stale.
// Regenerate with: go run ./cmd/medic gen-docs .
func TestGeneratedFilesUpToDate(t *testing.T) {
	root := filepath.Join("..", "..")
	want := map[string]string{
		"docs/config.md":           docs.ConfigMarkdown(),
		"schema/medic.schema.json": string(docs.MarshalSchema(docs.ConfigSchema())),
	}
	for _, typ := range check.Types() {
		want["docs/checks/"+typ.Name+".md"] = "<!-- Generated by `medic gen-docs`. Do not edit. -->\n\n" + docs.TypeMarkdown(typ)
	}
	for p, w := range want {
		got, err := os.ReadFile(filepath.Join(root, p))
		if err != nil || string(got) != w {
			t.Errorf("%s is stale; run: go run ./cmd/medic gen-docs .", p)
		}
	}
}
